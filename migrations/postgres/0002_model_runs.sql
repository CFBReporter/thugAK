-- The model's training log: one row per weekly training run per league.
--
-- A run trains a candidate (refitted settings + a correction layer learned
-- from replayed games) and compares it with the active model on recent games
-- neither was fitted on. `promoted` says whether the candidate went live; the
-- active model for a league is its latest promoted row. Rejected candidates
-- are kept, so the log shows every attempt, not only the successes.
CREATE TABLE IF NOT EXISTS model_runs (
    run_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league      TEXT NOT NULL,
    version     TEXT NOT NULL,
    trained_at  TEXT NOT NULL,
    promoted    INTEGER NOT NULL DEFAULT 0,
    model       TEXT,
    metrics     TEXT,
    changes     TEXT,
    note        TEXT
);
CREATE INDEX IF NOT EXISTS ix_model_runs_league ON model_runs(league, trained_at);

ALTER TABLE model_runs ENABLE ROW LEVEL SECURITY;
